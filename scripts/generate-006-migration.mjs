/**
 * Builds supabase/migrations/006_products_columns.sql.
 *
 * Moves data that used to live in JSON files under the public `config/` storage folder
 * (product keys, brands, hidden flags, category order) into real database columns/tables.
 * Reads the current files through their public URLs, so no secrets are needed.
 *
 * Usage: node scripts/generate-006-migration.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const envText = readFileSync(path.join(root, '.env.local'), 'utf8')
const baseUrl = envText
  .split('\n')
  .find((l) => l.startsWith('VITE_SUPABASE_URL='))
  ?.slice('VITE_SUPABASE_URL='.length)
  .trim()
if (!baseUrl) throw new Error('Missing VITE_SUPABASE_URL in .env.local')

async function readConfig(name) {
  const res = await fetch(`${baseUrl}/storage/v1/object/public/product-images/config/${name}.json`)
  if (!res.ok) return null
  const text = await res.text()
  return text.trim() ? JSON.parse(text) : null
}

const sql = (value) => `'${String(value).replaceAll("'", "''")}'`

const keysFile = (await readConfig('product-keys')) ?? { lastNumber: 0, keys: {} }
const brandsFile = (await readConfig('product-brands')) ?? { brands: {} }
const hiddenFile = (await readConfig('hidden-product-ids')) ?? { ids: [] }
const orderFile = (await readConfig('category-order')) ?? { categories: [] }

const keyRows = Object.entries(keysFile.keys).map(([id, key]) => `(${sql(id)}, ${sql(key)})`)
const brandRows = Object.entries(brandsFile.brands)
  .filter(([, brand]) => brand.trim())
  .map(([id, brand]) => `(${sql(id)}, ${sql(brand.trim())})`)
const hiddenIds = hiddenFile.ids.map(sql)
const orderRows = orderFile.categories.map((category, i) => `(${sql(category)}, ${i})`)

const parts = []
parts.push(`-- Moves app settings out of public storage JSON files (config/*.json) into the database.
-- Generated by scripts/generate-006-migration.mjs. Safe to re-run.

alter table public.products add column if not exists product_key text;
alter table public.products add column if not exists brand text not null default '';
alter table public.products add column if not exists hidden boolean not null default false;

create sequence if not exists public.products_key_seq;

create table if not exists public.category_order (
  category text primary key,
  position integer not null
);

alter table public.category_order enable row level security;

drop policy if exists "category_order_select" on public.category_order;
create policy "category_order_select"
  on public.category_order for select
  to anon, authenticated
  using (true);

drop policy if exists "category_order_write" on public.category_order;
create policy "category_order_write"
  on public.category_order for all
  to authenticated
  using (true)
  with check (true);
`)

if (keyRows.length) {
  parts.push(`-- Product keys (0001, 0002, …) from config/product-keys.json
update public.products p
set product_key = v.key
from (values
  ${keyRows.join(',\n  ')}
) as v(id, key)
where p.id = v.id::uuid and p.product_key is null;
`)
}

if (brandRows.length) {
  parts.push(`-- Brands from config/product-brands.json
update public.products p
set brand = v.brand
from (values
  ${brandRows.join(',\n  ')}
) as v(id, brand)
where p.id = v.id::uuid and p.brand = '';
`)
}

if (hiddenIds.length) {
  parts.push(`-- Hidden products from config/hidden-product-ids.json
update public.products set hidden = true where id in (${hiddenIds.join(', ')});
`)
}

if (orderRows.length) {
  parts.push(`-- Category order from config/category-order.json
insert into public.category_order (category, position) values
  ${orderRows.join(',\n  ')}
on conflict (category) do update set position = excluded.position;
`)
}

parts.push(`-- Continue numbering after the highest key ever issued (numbers of deleted products are never reused).
do $$
declare
  last_n integer := ${Number(keysFile.lastNumber) || 0};
  max_n integer;
begin
  select coalesce(max(product_key::integer), 0) into max_n
  from public.products
  where product_key ~ '^[0-9]+$';
  last_n := greatest(last_n, max_n);
  perform setval('public.products_key_seq', greatest(last_n, 1), last_n > 0);

  -- Any product still without a key gets the next number, oldest first.
  update public.products p
  set product_key = lpad(n.next_n::text, 4, '0')
  from (
    select id, nextval('public.products_key_seq') as next_n
    from (select id from public.products where product_key is null order by created_at, id) s
  ) n
  where p.id = n.id;
end $$;

alter table public.products
  alter column product_key set default lpad(nextval('public.products_key_seq')::text, 4, '0');
alter table public.products alter column product_key set not null;
create unique index if not exists products_product_key_unique on public.products (product_key);

notify pgrst, 'reload schema';
`)

const out = path.join(root, 'supabase', 'migrations', '006_products_columns.sql')
writeFileSync(out, parts.join('\n'))
console.log(
  `Wrote ${out}: ${keyRows.length} keys, ${brandRows.length} brands, ${hiddenIds.length} hidden, ${orderRows.length} categories.`,
)
