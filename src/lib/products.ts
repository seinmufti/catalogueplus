import {
  PRODUCT_IMAGES_BUCKET,
  supabase,
  supabaseConfigError,
} from '@/lib/supabase'
import {
  getWatermarkedImageUrl,
  removeWatermarkedImage,
  uploadWatermarkedImage,
} from '@/lib/watermarkedImages'
import type { NewProductInput, Product, UpdateProductInput } from '@/types/product'

export type CreateProductPhase = 'upload' | 'save'

type CreateProductOptions = {
  onPhase?: (phase: CreateProductPhase) => void
}

function assertSupabase() {
  if (!supabase) {
    throw new Error(supabaseConfigError ?? 'Supabase is not configured.')
  }
  return supabase
}

const DUPLICATE_NAME_MESSAGE = 'A product with this name already exists.'

/** The `name` column is unique in the database, which is what actually enforces this. */
function isDuplicateNameError(err: unknown): boolean {
  return (err as { code?: string } | null)?.code === '23505'
}

function extensionFromFile(file: File): string {
  const fromName = file.name.split('.').pop()?.toLowerCase()
  if (fromName && /^[a-z0-9]+$/.test(fromName)) return fromName
  const fromMime = file.type.split('/').pop()?.toLowerCase()
  if (fromMime === 'jpeg') return 'jpg'
  if (fromMime) return fromMime
  return 'jpg'
}

/** Upload the original file byte-for-byte, then its watermarked copy. Returns the original's path. */
async function uploadOriginalWithWatermark(
  client: ReturnType<typeof assertSupabase>,
  original: File,
): Promise<string> {
  const objectPath = `${crypto.randomUUID()}.${extensionFromFile(original)}`
  const { error: uploadError } = await client.storage
    .from(PRODUCT_IMAGES_BUCKET)
    .upload(objectPath, original, {
      cacheControl: '3600',
      upsert: false,
      contentType: original.type || 'image/jpeg',
    })
  if (uploadError) throw uploadError

  try {
    await uploadWatermarkedImage(client, objectPath, original)
  } catch {
    // Missing copies are regenerated by ensureWatermarkedImages on the next admin load.
  }
  return objectPath
}

async function removeProductImageFiles(
  client: ReturnType<typeof assertSupabase>,
  imagePath: string,
): Promise<void> {
  await client.storage.from(PRODUCT_IMAGES_BUCKET).remove([imagePath])
  await removeWatermarkedImage(client, imagePath)
}

export function getProductWatermarkedImageUrl(imagePath: string | null): string | null {
  if (!supabase) return null
  return getWatermarkedImageUrl(supabase, imagePath)
}

export function getPublicImageUrl(imagePath: string | null): string | null {
  if (!imagePath) return null
  if (imagePath.startsWith('blob:') || imagePath.startsWith('http://') || imagePath.startsWith('https://')) {
    return imagePath
  }
  const client = assertSupabase()
  const { data } = client.storage.from(PRODUCT_IMAGES_BUCKET).getPublicUrl(imagePath)
  return data.publicUrl
}

export function distinctCategoriesFromProducts(products: Product[]): string[] {
  const unique = [...new Set(products.map((p) => p.category.trim()).filter(Boolean))]
  unique.sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }))
  return unique
}

export function distinctBrandsFromProducts(products: Product[]): string[] {
  const unique = [...new Set(products.map((p) => p.brand.trim()).filter(Boolean))]
  unique.sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }))
  return unique
}

export async function listProducts(): Promise<Product[]> {
  const { data, error } = await assertSupabase()
    .from('products')
    .select('*')
    .order('product_key', { ascending: true })

  if (error) throw error
  return (data ?? []) as Product[]
}

/** Products visible on the customer catalogue (not hidden). */
export async function listCatalogueProducts(): Promise<Product[]> {
  const { data, error } = await assertSupabase()
    .from('products')
    .select('*')
    .eq('hidden', false)
    .order('product_key', { ascending: true })

  if (error) throw error
  return (data ?? []) as Product[]
}

export async function setProductHidden(id: string, hidden: boolean): Promise<void> {
  // `.single()` makes a silently rejected update (0 rows, e.g. signed out) an error.
  const { error } = await assertSupabase()
    .from('products')
    .update({ hidden })
    .eq('id', id)
    .select('id')
    .single()
  if (error) throw error
}

export async function createProduct(
  input: NewProductInput,
  options?: CreateProductOptions,
): Promise<Product> {
  const client = assertSupabase()

  options?.onPhase?.('upload')
  const objectPath = await uploadOriginalWithWatermark(client, input.image)

  options?.onPhase?.('save')
  // product_key is assigned by the database.
  const { data, error } = await client
    .from('products')
    .insert({
      name: input.name.trim(),
      category: input.category.trim(),
      brand: input.brand.trim(),
      quantity_in_carton: input.quantityInCarton,
      image_path: objectPath,
    })
    .select('*')
    .single()

  if (error) {
    await removeProductImageFiles(client, objectPath)
    if (isDuplicateNameError(error)) throw new Error(DUPLICATE_NAME_MESSAGE)
    throw error
  }

  return data as Product
}

export async function updateProduct(
  id: string,
  input: UpdateProductInput,
  options?: CreateProductOptions,
): Promise<Product> {
  const client = assertSupabase()

  let previousImagePath: string | null = null
  let imagePath: string | undefined
  let uploadedPath: string | null = null

  if (input.image) {
    const { data: existing, error: fetchError } = await client
      .from('products')
      .select('image_path')
      .eq('id', id)
      .single()
    if (fetchError) throw fetchError
    previousImagePath = (existing as { image_path: string | null }).image_path

    options?.onPhase?.('upload')
    uploadedPath = await uploadOriginalWithWatermark(client, input.image)
    imagePath = uploadedPath
  }

  options?.onPhase?.('save')
  const { data, error } = await client
    .from('products')
    .update({
      name: input.name.trim(),
      category: input.category.trim(),
      brand: input.brand.trim(),
      quantity_in_carton: input.quantityInCarton,
      ...(imagePath ? { image_path: imagePath } : {}),
    })
    .eq('id', id)
    .select('*')
    .single()

  if (error) {
    if (uploadedPath) await removeProductImageFiles(client, uploadedPath)
    if (isDuplicateNameError(error)) throw new Error(DUPLICATE_NAME_MESSAGE)
    throw error
  }

  if (uploadedPath && previousImagePath) {
    await removeProductImageFiles(client, previousImagePath)
  }

  return data as Product
}

export async function deleteProduct(id: string): Promise<void> {
  const client = assertSupabase()
  const { data: existing, error: fetchError } = await client
    .from('products')
    .select('image_path')
    .eq('id', id)
    .single()

  if (fetchError) throw fetchError

  const { data: deleted, error } = await client.from('products').delete().eq('id', id).select('id')
  if (error) throw error
  if (!deleted?.length) throw new Error('Could not delete the product. Sign in again and retry.')

  const imagePath = (existing as { image_path: string | null }).image_path
  if (imagePath) {
    await removeProductImageFiles(client, imagePath)
  }
}
